export const PANEL_LOCALES: Record<string, Dict> = {
  en, es, de, fr, ja, ko, pl, 'pt-BR': ptBR, tr, uk, 'zh-CN': zhCN, 'zh-TW': zhTW,
};

/** Exact tag first (`pt-BR`, `zh-TW`), then the language alone, then English. */
export const pickDictionary = (locale: string | null | undefined): Dict => {
  const tag = (locale || '').trim();
  if (PANEL_LOCALES[tag]) return PANEL_LOCALES[tag];
  const language = tag.split('-')[0]?.toLowerCase() ?? '';
  if (language === 'zh') return /tw|hk|hant/i.test(tag) ? zhTW : zhCN;
  if (language === 'pt') return ptBR;
  return PANEL_LOCALES[language] ?? en;
};

export const format = (template: string, values: Record<string, string | number>): string =>
  template.replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
